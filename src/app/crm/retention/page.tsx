'use client';

import React, { useState, useEffect, useCallback, useRef } from 'react';
import {
    Phone,
    Mail,
    Calendar,
    Clock,
    User,
    AlertTriangle,
    CheckCircle2,
    Zap,
    TrendingUp,
    Target,
    Plus,
    RefreshCw,
    ChevronRight,
    MessageSquare,
    PhoneCall,
    Loader2,
    X,
    PlayCircle,
    GripVertical,
    SkipForward,
    ArrowRight,
    MapPin,
    DollarSign,
    Activity,
    Truck,
    Upload,
    ShieldCheck,
    Snowflake,
    HeartCrack
} from 'lucide-react';
import { cn } from '@/lib/utils';
import toast from 'react-hot-toast';
import { useRouter } from 'next/navigation';
import { PageHeader } from '@/components/ui/PageHeader';
import { ListTodo, GitBranch } from 'lucide-react';

interface Task {
    _id: string;
    client: string;
    clientInfo?: {
        _id: string;
        name: string;
        phones?: { value: string; label: string }[];
        emails?: { value: string; label: string }[];
    };
    type: string;
    status: 'Pending' | 'In Progress' | 'Completed' | 'Skipped' | 'Overdue';
    priority: 'Low' | 'Medium' | 'High' | 'Critical';
    dueDate: string;
    assignedTo?: string;
    assignedToInfo?: { _id: string; firstName: string; lastName: string };
    notes?: string;
    outcome?: string;
    autoGenerated?: boolean;
    triggerReason?: string;
    createdAt: string;
    completedAt?: string;
}

interface Stats {
    byStatus: { _id: string; count: number }[];
    overdue: number;
}

interface Client {
    _id: string;
    name: string;
    contactStatus?: string;
    contactType?: string;
    totalRevenue?: number;
    balance?: number;
    activityCount?: number;
    lastActivity?: string;
    phones?: { value: string; label: string }[];
    emails?: { value: string; label: string }[];
}

type KanbanColumn = 'Pending' | 'In Progress' | 'Completed';

const COLUMNS: { id: KanbanColumn; label: string; color: string; bgColor: string; icon: React.ReactNode }[] = [
    { id: 'Pending', label: 'TO DO', color: 'text-amber-600', bgColor: 'bg-amber-50 border-amber-200', icon: <Clock className="w-4 h-4" /> },
    { id: 'In Progress', label: 'IN PROGRESS', color: 'text-blue-600', bgColor: 'bg-blue-50 border-blue-200', icon: <PlayCircle className="w-4 h-4" /> },
    { id: 'Completed', label: 'DONE', color: 'text-emerald-600', bgColor: 'bg-emerald-50 border-emerald-200', icon: <CheckCircle2 className="w-4 h-4" /> },
];

const priorityColors = {
    Low: 'border-l-slate-300',
    Medium: 'border-l-blue-500',
    High: 'border-l-orange-500',
    Critical: 'border-l-red-500'
};

const typeIcons: { [key: string]: React.ReactNode } = {
    'Followup Call': <PhoneCall className="w-3.5 h-3.5" />,
    'Followup Email': <Mail className="w-3.5 h-3.5" />,
    'Check-in': <MessageSquare className="w-3.5 h-3.5" />,
    'Re-engagement': <RefreshCw className="w-3.5 h-3.5" />,
    'Win-back': <Target className="w-3.5 h-3.5" />,
    'Feedback Request': <MessageSquare className="w-3.5 h-3.5" />,
    'Upsell Opportunity': <TrendingUp className="w-3.5 h-3.5" />
};

const PIPELINE_STAGES = [
    { id: 'Initial Contact', label: 'Initial Contact', color: 'text-slate-600', bgColor: 'bg-slate-50 border-slate-200', icon: <User className="w-4 h-4" /> },
    { id: 'Sampling', label: 'Sampling', color: 'text-purple-600', bgColor: 'bg-purple-50 border-purple-200', icon: <Activity className="w-4 h-4" /> },
    { id: 'New Prospect', label: 'New Prospect', color: 'text-blue-600', bgColor: 'bg-blue-50 border-blue-200', icon: <TrendingUp className="w-4 h-4" /> },
    { id: 'Closed won', label: 'Closed Won', color: 'text-emerald-600', bgColor: 'bg-emerald-50 border-emerald-200', icon: <CheckCircle2 className="w-4 h-4" /> },
    { id: 'Closed lost', label: 'Closed Lost', color: 'text-red-600', bgColor: 'bg-red-50 border-red-200', icon: <X className="w-4 h-4" /> },
    { id: 'Uncategorized', label: 'Uncategorized', color: 'text-slate-400', bgColor: 'bg-white border-slate-100', icon: <Clock className="w-4 h-4" /> },
];


function HeaderStatItem({ icon: Icon, value, label, colorClass, gradientClass }: { icon: any, value: string | number, label: string, colorClass: string, gradientClass: string }) {
    return (
        <div className="flex items-center space-x-2.5 px-3 py-1 border-r border-slate-100 last:border-0">
            <div className={cn("w-7 h-7 flex items-center justify-center rounded-lg shadow-sm text-white", gradientClass)}>
                <Icon className="w-4 h-4" />
            </div>
            <div className="flex flex-col">
                <span className="text-xs font-black text-slate-900 leading-none">{value}</span>
                <span className={cn("text-[8px] font-bold uppercase tracking-wider", colorClass)}>{label}</span>
            </div>
        </div>
    );
}

export default function RetentionKanbanPage() {
    const router = useRouter();
    const [tasks, setTasks] = useState<Task[]>([]);
    const [stats, setStats] = useState<Stats | null>(null);
    const [loading, setLoading] = useState(true);
    const [generating, setGenerating] = useState(false);
    const [users, setUsers] = useState<{ _id: string; firstName: string; lastName: string }[]>([]);
    const [clients, setClients] = useState<Client[]>([]);

    // Drag state
    const [draggedTask, setDraggedTask] = useState<Task | null>(null);
    const [dragOverColumn, setDragOverColumn] = useState<KanbanColumn | null>(null);

    const [draggedClient, setDraggedClient] = useState<Client | null>(null);
    const [dragOverStage, setDragOverStage] = useState<string | null>(null);

    // Modal
    const [isModalOpen, setIsModalOpen] = useState(false);
    const [selectedTask, setSelectedTask] = useState<Task | null>(null);
    const [outcomeText, setOutcomeText] = useState('');
    const [isSubmitting, setIsSubmitting] = useState(false);

    // New Task Modal
    const [isNewTaskModalOpen, setIsNewTaskModalOpen] = useState(false);
    const [newTask, setNewTask] = useState({
        client: '',
        type: 'Check-in',
        priority: 'Medium',
        dueDate: new Date().toISOString().split('T')[0],
        assignedTo: '',
        notes: ''
    });

    const [activeTab, setActiveTab] = useState('tasks');

    const inactivityStats = React.useMemo(() => {
        const now = Date.now();
        const dayMs = 24 * 60 * 60 * 1000;
        const relevantClients = clients.filter(c => (c.totalRevenue || 0) >= 100);
        
        let i30 = 0, i60 = 0, i90 = 0;
        relevantClients.forEach(c => {
            const time = c.lastActivity ? new Date(c.lastActivity).getTime() : 0;
            const diff = time === 0 ? 999 * dayMs : now - time;
            const days = Math.floor(diff / dayMs);
            if (days > 90) i90++;
            else if (days > 60) i60++;
            else if (days > 30) i30++;
        });
        const total = relevantClients.length;
        const active = total - i30 - i60 - i90;
        const rate = total > 0 ? Math.round((active / total) * 100) : 100;
        return { i30, i60, i90, total, active, rate };
    }, [clients]);

    useEffect(() => {
        fetchTasks();
        fetchUsers();
        fetchClients();
    }, []);

    const fetchTasks = useCallback(async () => {
        try {
            setLoading(true);
            const res = await fetch(`/api/crm/retention?limit=200`);
            const data = await res.json();
            setTasks(data.tasks || []);
            setStats(data.stats || null);
        } catch (error) {
            console.error('Error fetching tasks:', error);
            toast.error('Failed to load tasks');
        } finally {
            setLoading(false);
        }
    }, []);

    const fetchUsers = async () => {
        try {
            const res = await fetch('/api/users?limit=100');
            const data = await res.json();
            setUsers(data.users || []);
        } catch (e) {
            console.error('Failed to fetch users', e);
        }
    };

    const fetchClients = async () => {
        try {
            const res = await fetch('/api/clients?limit=500');
            const data = await res.json();
            setClients(data.clients || []);
        } catch (e) {
            console.error('Failed to fetch clients', e);
        }
    };

    const handleAutoGenerate = async () => {
        try {
            setGenerating(true);
            const res = await fetch('/api/crm/retention/auto-generate', { method: 'POST' });
            const data = await res.json();
            toast.success(`Created ${data.tasksCreated} tasks (${data.tasksAssigned} auto-assigned)`);
            fetchTasks();
        } catch (error) {
            console.error('Auto-generate error:', error);
            toast.error('Failed to generate tasks');
        } finally {
            setGenerating(false);
        }
    };

    const handleUpdateTask = async (taskId: string, updates: Partial<Task>) => {
        try {
            const res = await fetch(`/api/crm/retention/${taskId}`, {
                method: 'PATCH',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify(updates)
            });
            if (res.ok) {
                // Optimistic update
                setTasks(prev => prev.map(t => t._id === taskId ? { ...t, ...updates } : t));
                return true;
            }
            return false;
        } catch (error) {
            console.error('Update error:', error);
            return false;
        }
    };

    // Drag & Drop Handlers
    const handleDragStart = (e: React.DragEvent, task: Task) => {
        setDraggedTask(task);
        e.dataTransfer.effectAllowed = 'move';
        e.dataTransfer.setData('text/plain', task._id);
    };

    const handleDragOver = (e: React.DragEvent, column: KanbanColumn) => {
        e.preventDefault();
        e.dataTransfer.dropEffect = 'move';
        setDragOverColumn(column);
    };

    const handleDragLeave = () => {
        setDragOverColumn(null);
    };

    const handleDrop = async (e: React.DragEvent, targetColumn: KanbanColumn) => {
        e.preventDefault();
        setDragOverColumn(null);

        if (!draggedTask || draggedTask.status === targetColumn) {
            setDraggedTask(null);
            return;
        }

        // Optimistic update
        const previousStatus = draggedTask.status;
        setTasks(prev => prev.map(t => 
            t._id === draggedTask._id ? { ...t, status: targetColumn } : t
        ));

        const updates: Partial<Task> = { status: targetColumn };
        if (targetColumn === 'Completed') {
            updates.completedAt = new Date().toISOString();
        }

        const success = await handleUpdateTask(draggedTask._id, updates);
        
        if (!success) {
            // Revert on failure
            setTasks(prev => prev.map(t => 
                t._id === draggedTask._id ? { ...t, status: previousStatus } : t
            ));
            toast.error('Failed to move task');
        } else {
            toast.success(`Task moved to ${targetColumn}`);
        }

        setDraggedTask(null);
    };

    const handleDragEnd = () => {
        setDraggedTask(null);
        setDragOverColumn(null);
    };

    const handleClientDragStart = (e: React.DragEvent, client: Client) => {
        setDraggedClient(client);
        e.dataTransfer.effectAllowed = 'move';
    };

    const handleClientDragOver = (e: React.DragEvent, stageId: string) => {
        e.preventDefault();
        setDragOverStage(stageId);
    };

    const handleClientDrop = async (e: React.DragEvent, targetStatus: string) => {
        e.preventDefault();
        setDragOverStage(null);

        if (!draggedClient || (draggedClient.contactStatus || 'Uncategorized') === targetStatus) {
            setDraggedClient(null);
            return;
        }

        const previousStatus = draggedClient.contactStatus;
        setClients(prev => prev.map(c => 
            c._id === draggedClient._id ? { ...c, contactStatus: targetStatus } : c
        ));

        try {
            const res = await fetch(`/api/clients/${draggedClient._id}`, {
                method: 'PATCH',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ contactStatus: targetStatus })
            });
            if (!res.ok) throw new Error('Failed to update status');
            toast.success(`Client moved to ${targetStatus}`);
        } catch (error) {
            setClients(prev => prev.map(c => 
                c._id === draggedClient._id ? { ...c, contactStatus: previousStatus } : c
            ));
            toast.error('Failed to update client status');
        }
        setDraggedClient(null);
    };

    const handleCompleteTask = async () => {
        if (!selectedTask) return;
        setIsSubmitting(true);
        const success = await handleUpdateTask(selectedTask._id, {
            status: 'Completed',
            outcome: outcomeText
        });
        if (success) {
            toast.success('Task completed');
            setIsModalOpen(false);
            setSelectedTask(null);
            setOutcomeText('');
            fetchTasks();
        } else {
            toast.error('Failed to complete task');
        }
        setIsSubmitting(false);
    };

    const handleCreateTask = async (e: React.FormEvent) => {
        e.preventDefault();
        setIsSubmitting(true);
        try {
            const res = await fetch('/api/crm/retention', {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify(newTask)
            });
            if (res.ok) {
                toast.success('Task created');
                setIsNewTaskModalOpen(false);
                setNewTask({
                    client: '',
                    type: 'Check-in',
                    priority: 'Medium',
                    dueDate: new Date().toISOString().split('T')[0],
                    assignedTo: '',
                    notes: ''
                });
                fetchTasks();
            } else {
                toast.error('Failed to create task');
            }
        } catch (error) {
            toast.error('Error creating task');
        } finally {
            setIsSubmitting(false);
        }
    };

    const openTaskModal = (task: Task) => {
        setSelectedTask(task);
        setOutcomeText(task.outcome || '');
        setIsModalOpen(true);
    };

    const getColumnTasks = (status: KanbanColumn) => {
        // Include Overdue in Pending column
        if (status === 'Pending') {
            return tasks.filter(t => t.status === 'Pending' || t.status === 'Overdue');
        }
        return tasks.filter(t => t.status === status);
    };

    const getStatusCount = (status: string) => {
        if (status === 'Pending') {
            return tasks.filter(t => t.status === 'Pending' || t.status === 'Overdue').length;
        }
        return tasks.filter(t => t.status === status).length;
    };

    const formatDate = (dateStr: string) => {
        const date = new Date(dateStr);
        const today = new Date();
        today.setHours(0, 0, 0, 0);
        const taskDate = new Date(dateStr);
        taskDate.setHours(0, 0, 0, 0);

        const diff = Math.floor((taskDate.getTime() - today.getTime()) / (1000 * 60 * 60 * 24));

        if (diff < 0) return `${Math.abs(diff)}d overdue`;
        if (diff === 0) return 'Today';
        if (diff === 1) return 'Tomorrow';
        return date.toLocaleDateString('en-US', { month: 'short', day: 'numeric' });
    };

    const isOverdue = (task: Task) => {
        return task.status === 'Overdue' || (new Date(task.dueDate) < new Date(new Date().setHours(0, 0, 0, 0)) && task.status !== 'Completed' && task.status !== 'Skipped');
    };

    return (
        <div className="flex flex-col h-[calc(100vh-40px)] bg-slate-100 overflow-hidden">
            <PageHeader
                title=""
                activeTab={activeTab}
                onTabChange={setActiveTab}
                tabs={[
                    { id: 'tasks', label: 'Tasks', icon: ListTodo },
                    { id: 'lead-pipeline', label: 'Lead Pipeline', icon: GitBranch },
                    { id: 'client-pipeline', label: 'Client Pipeline', icon: GitBranch },
                ]}
                stats={
                    <div className="flex items-center">
                        <HeaderStatItem 
                            icon={ShieldCheck} 
                            value={`${inactivityStats.rate}%`} 
                            label="Retention" 
                            colorClass="text-emerald-600" 
                            gradientClass="bg-gradient-to-br from-emerald-500 to-teal-600" 
                        />
                        <HeaderStatItem 
                            icon={Clock} 
                            value={inactivityStats.i30} 
                            label="Warm" 
                            colorClass="text-amber-600" 
                            gradientClass="bg-gradient-to-br from-amber-500 to-yellow-600" 
                        />
                        <HeaderStatItem 
                            icon={Snowflake} 
                            value={inactivityStats.i60} 
                            label="Cold" 
                            colorClass="text-orange-600" 
                            gradientClass="bg-gradient-to-br from-orange-500 to-red-600" 
                        />
                        <HeaderStatItem 
                            icon={HeartCrack} 
                            value={inactivityStats.i90} 
                            label="Lost" 
                            colorClass="text-red-600" 
                            gradientClass="bg-gradient-to-br from-red-500 to-rose-600" 
                        />
                        <div className="w-px h-8 bg-slate-200 mx-4" />
                        <div className="flex items-center space-x-2 text-xs text-slate-500 mr-4">
                            <AlertTriangle className="w-3.5 h-3.5 text-red-500" />
                            <span className="font-bold text-red-600">
                                {tasks.filter(t => isOverdue(t)).length}
                            </span>
                            <span className="uppercase font-bold tracking-wider text-[9px]">Overdue</span>
                        </div>
                    </div>
                }
                actions={
                    <>
                        <button
                            onClick={handleAutoGenerate}
                            disabled={generating}
                            className="flex items-center space-x-2 px-4 py-2 bg-gradient-to-r from-orange-500 to-red-500 text-white text-xs font-bold uppercase hover:from-orange-600 hover:to-red-600 transition-all disabled:opacity-50 shadow-sm"
                        >
                            {generating ? <Loader2 className="w-4 h-4 animate-spin" /> : <Zap className="w-4 h-4" />}
                            <span>Auto-Generate</span>
                        </button>
                        <button
                            onClick={() => setIsNewTaskModalOpen(true)}
                            className="flex items-center space-x-2 px-4 py-2 bg-black text-white text-xs font-bold uppercase hover:bg-slate-800 transition-colors shadow-sm"
                        >
                            <Plus className="w-4 h-4" />
                            <span>New Task</span>
                        </button>
                    </>
                }
            />

            {/* Kanban Board - Tasks Tab */}
            {activeTab === 'tasks' && (
                <div className="flex-1 overflow-x-auto p-6">
                {loading ? (
                    <div className="flex items-center justify-center h-full">
                        <Loader2 className="w-8 h-8 animate-spin text-slate-400" />
                    </div>
                ) : (
                    <div className="flex space-x-4 h-full min-w-max">
                        {COLUMNS.map((column) => (
                            <div
                                key={column.id}
                                className={cn(
                                    "flex flex-col w-[360px] bg-white border shadow-sm h-full transition-all",
                                    dragOverColumn === column.id && "ring-2 ring-blue-400 ring-offset-2"
                                )}
                                onDragOver={(e) => handleDragOver(e, column.id)}
                                onDragLeave={handleDragLeave}
                                onDrop={(e) => handleDrop(e, column.id)}
                            >
                                {/* Column Header */}
                                <div className={cn("px-4 py-3 border-b flex items-center justify-between shrink-0", column.bgColor)}>
                                    <div className="flex items-center space-x-2">
                                        <span className={column.color}>{column.icon}</span>
                                        <span className={cn("text-xs font-black uppercase tracking-wider", column.color)}>{column.label}</span>
                                    </div>
                                    <span className={cn("text-sm font-black", column.color)}>{getStatusCount(column.id)}</span>
                                </div>

                                {/* Column Content */}
                                <div className="flex-1 overflow-y-auto p-3 space-y-2 scrollbar-custom">
                                    {getColumnTasks(column.id).length === 0 ? (
                                        <div className="flex flex-col items-center justify-center py-8 text-slate-400">
                                            <div className="w-12 h-12 bg-slate-100 flex items-center justify-center mb-2">
                                                {column.icon}
                                            </div>
                                            <p className="text-[10px] font-bold uppercase">No tasks</p>
                                        </div>
                                    ) : (
                                        getColumnTasks(column.id).map((task) => (
                                            <div
                                                key={task._id}
                                                draggable
                                                onDragStart={(e) => handleDragStart(e, task)}
                                                onDragEnd={handleDragEnd}
                                                onClick={() => openTaskModal(task)}
                                                className={cn(
                                                    "bg-white border border-l-4 p-3 cursor-grab active:cursor-grabbing hover:shadow-md transition-all group",
                                                    priorityColors[task.priority],
                                                    draggedTask?._id === task._id && "opacity-50 scale-95",
                                                    isOverdue(task) && "bg-red-50/50"
                                                )}
                                            >
                                                {/* Task Header */}
                                                <div className="flex items-start justify-between mb-2">
                                                    <div className="flex items-center space-x-2">
                                                        <div className={cn(
                                                            "w-6 h-6 flex items-center justify-center",
                                                            task.priority === 'Critical' ? "bg-red-100 text-red-600" :
                                                            task.priority === 'High' ? "bg-orange-100 text-orange-600" :
                                                            task.priority === 'Medium' ? "bg-blue-100 text-blue-600" :
                                                            "bg-slate-100 text-slate-600"
                                                        )}>
                                                            {typeIcons[task.type] || <Target className="w-3 h-3" />}
                                                        </div>
                                                        <span className="text-[10px] font-bold text-slate-600 uppercase">{task.type}</span>
                                                    </div>
                                                    <GripVertical className="w-4 h-4 text-slate-300 opacity-0 group-hover:opacity-100 transition-opacity" />
                                                </div>

                                                {/* Client Name */}
                                                <div className="text-sm font-bold text-slate-800 mb-2 truncate">
                                                    {task.clientInfo?.name || 'Unknown Client'}
                                                </div>

                                                {/* Notes Preview */}
                                                {task.notes && (
                                                    <p className="text-[10px] text-slate-500 line-clamp-2 mb-2">{task.notes}</p>
                                                )}

                                                {/* Auto-generated badge */}
                                                {task.autoGenerated && (
                                                    <div className="flex items-center space-x-1 mb-2">
                                                        <Zap className="w-2.5 h-2.5 text-orange-500" />
                                                        <span className="text-[9px] font-bold text-orange-600 uppercase">{task.triggerReason}</span>
                                                    </div>
                                                )}

                                                {/* Footer */}
                                                <div className="flex items-center justify-between pt-2 border-t border-slate-100">
                                                    <div className="flex items-center space-x-1">
                                                        <Calendar className="w-3 h-3 text-slate-400" />
                                                        <span className={cn(
                                                            "text-[10px] font-bold",
                                                            isOverdue(task) ? "text-red-600" : "text-slate-500"
                                                        )}>
                                                            {formatDate(task.dueDate)}
                                                        </span>
                                                    </div>
                                                    {task.assignedToInfo && (
                                                        <div className="flex items-center space-x-1">
                                                            <div className="w-5 h-5 bg-slate-200 flex items-center justify-center text-[8px] font-black text-slate-600">
                                                                {task.assignedToInfo.firstName?.charAt(0)}
                                                            </div>
                                                        </div>
                                                    )}
                                                </div>
                                            </div>
                                        ))
                                    )}
                                </div>
                            </div>
                        ))}
                    </div>
                )}
            </div>
            )}

            {/* Lead Pipeline Tab Content */}
            {activeTab === 'lead-pipeline' && (
                <PipelineGridView 
                    clients={clients.filter(c => c.contactType === 'Potential Customer' || !c.contactType)} 
                    onClientClick={(client) => router.push(`/crm/clients/${client._id}`)}
                    onClientDrop={handleClientDrop}
                    draggedClient={draggedClient}
                    setDraggedClient={setDraggedClient}
                    dragOverStage={dragOverStage}
                    setDragOverStage={setDragOverStage}
                />
            )}

            {/* Client Pipeline Tab Content */}
            {activeTab === 'client-pipeline' && (
                <PipelineGridView 
                    clients={clients.filter(c => c.contactType === 'Current Customer')} 
                    onClientClick={(client) => router.push(`/crm/clients/${client._id}`)}
                    onClientDrop={handleClientDrop}
                    draggedClient={draggedClient}
                    setDraggedClient={setDraggedClient}
                    dragOverStage={dragOverStage}
                    setDragOverStage={setDragOverStage}
                />
            )}

            {/* Task Detail Modal */}
            {isModalOpen && selectedTask && (
                <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/50 backdrop-blur-sm p-4">
                    <div className="bg-white w-full max-w-lg shadow-2xl animate-in fade-in zoom-in duration-200">
                        <div className="flex items-center justify-between px-6 py-4 border-b border-slate-100">
                            <div className="flex items-center space-x-3">
                                <div className={cn(
                                    "w-10 h-10 flex items-center justify-center",
                                    selectedTask.priority === 'Critical' ? "bg-red-100 text-red-600" :
                                    selectedTask.priority === 'High' ? "bg-orange-100 text-orange-600" :
                                    selectedTask.priority === 'Medium' ? "bg-blue-100 text-blue-600" :
                                    "bg-slate-100 text-slate-600"
                                )}>
                                    {typeIcons[selectedTask.type] || <Target className="w-5 h-5" />}
                                </div>
                                <div>
                                    <h2 className="text-sm font-black uppercase tracking-widest text-slate-900">{selectedTask.type}</h2>
                                    <span className={cn(
                                        "text-[9px] font-bold uppercase px-2 py-0.5",
                                        selectedTask.priority === 'Critical' ? "bg-red-100 text-red-700" :
                                        selectedTask.priority === 'High' ? "bg-orange-100 text-orange-700" :
                                        selectedTask.priority === 'Medium' ? "bg-blue-100 text-blue-700" :
                                        "bg-slate-100 text-slate-600"
                                    )}>
                                        {selectedTask.priority} Priority
                                    </span>
                                </div>
                            </div>
                            <button onClick={() => setIsModalOpen(false)} className="text-slate-400 hover:text-black">
                                <X className="w-5 h-5" />
                            </button>
                        </div>

                        <div className="p-6 space-y-4">
                            {/* Client Info */}
                            <div className="flex items-center space-x-3 p-3 bg-slate-50 border border-slate-100">
                                <div className="w-12 h-12 bg-slate-200 flex items-center justify-center text-sm font-black text-slate-600">
                                    {selectedTask.clientInfo?.name?.charAt(0) || '?'}
                                </div>
                                <div className="flex-1">
                                    <div className="text-sm font-bold text-slate-900">{selectedTask.clientInfo?.name || 'Unknown'}</div>
                                    <div className="flex items-center space-x-3 text-[11px] text-slate-500 mt-1">
                                        {selectedTask.clientInfo?.phones?.[0]?.value && (
                                            <a href={`tel:${selectedTask.clientInfo.phones[0].value}`} className="flex items-center hover:text-blue-600">
                                                <Phone className="w-3 h-3 mr-1" />{selectedTask.clientInfo.phones[0].value}
                                            </a>
                                        )}
                                        {selectedTask.clientInfo?.emails?.[0]?.value && (
                                            <a href={`mailto:${selectedTask.clientInfo.emails[0].value}`} className="flex items-center hover:text-blue-600">
                                                <Mail className="w-3 h-3 mr-1" />{selectedTask.clientInfo.emails[0].value}
                                            </a>
                                        )}
                                    </div>
                                </div>
                                <button
                                    onClick={() => router.push(`/crm/clients/${selectedTask.client}`)}
                                    className="px-3 py-1.5 bg-black text-white text-[10px] font-bold uppercase hover:bg-slate-800"
                                >
                                    View Profile
                                </button>
                            </div>

                            {/* Assigned To */}
                            {selectedTask.assignedToInfo && (
                                <div className="flex items-center space-x-2">
                                    <User className="w-4 h-4 text-slate-400" />
                                    <span className="text-xs text-slate-500">Assigned to:</span>
                                    <span className="text-xs font-bold text-slate-700">
                                        {selectedTask.assignedToInfo.firstName} {selectedTask.assignedToInfo.lastName}
                                    </span>
                                </div>
                            )}

                            {/* Details */}
                            <div className="grid grid-cols-2 gap-4 text-xs">
                                <div>
                                    <div className="text-[10px] font-bold text-slate-400 uppercase mb-1">Status</div>
                                    <span className={cn(
                                        "font-bold uppercase px-2 py-0.5",
                                        selectedTask.status === 'Completed' ? "bg-emerald-100 text-emerald-700" :
                                        selectedTask.status === 'In Progress' ? "bg-blue-100 text-blue-700" :
                                        selectedTask.status === 'Overdue' ? "bg-red-100 text-red-700" :
                                        "bg-amber-100 text-amber-700"
                                    )}>
                                        {selectedTask.status}
                                    </span>
                                </div>
                                <div>
                                    <div className="text-[10px] font-bold text-slate-400 uppercase mb-1">Due Date</div>
                                    <span className={cn("font-bold", isOverdue(selectedTask) ? "text-red-600" : "text-slate-700")}>
                                        {new Date(selectedTask.dueDate).toLocaleDateString()}
                                    </span>
                                </div>
                            </div>

                            {/* Notes */}
                            {selectedTask.notes && (
                                <div>
                                    <div className="text-[10px] font-bold text-slate-400 uppercase mb-1">Notes</div>
                                    <p className="text-xs text-slate-700 bg-slate-50 p-3 border border-slate-100">{selectedTask.notes}</p>
                                </div>
                            )}

                            {/* Auto-generated */}
                            {selectedTask.autoGenerated && (
                                <div className="flex items-center space-x-2 p-2 bg-orange-50 border border-orange-200">
                                    <Zap className="w-4 h-4 text-orange-500" />
                                    <span className="text-[10px] font-bold text-orange-700">Auto-generated: {selectedTask.triggerReason}</span>
                                </div>
                            )}

                            {/* Outcome */}
                            {selectedTask.status !== 'Completed' && (
                                <div>
                                    <div className="text-[10px] font-bold text-slate-400 uppercase mb-1">Outcome / Result</div>
                                    <textarea
                                        value={outcomeText}
                                        onChange={(e) => setOutcomeText(e.target.value)}
                                        placeholder="Describe the outcome of this task..."
                                        className="w-full px-3 py-2 text-sm border border-slate-200 focus:outline-none focus:border-black h-24 resize-none"
                                    />
                                </div>
                            )}
                        </div>

                        <div className="px-6 py-4 border-t border-slate-100 bg-slate-50 flex justify-between">
                            <div className="flex items-center space-x-2">
                                {selectedTask.status !== 'Completed' && (
                                    <>
                                        {selectedTask.status === 'Pending' && (
                                            <button
                                                onClick={async () => {
                                                    await handleUpdateTask(selectedTask._id, { status: 'In Progress' });
                                                    setIsModalOpen(false);
                                                    fetchTasks();
                                                }}
                                                className="flex items-center space-x-1 px-3 py-2 bg-blue-600 text-white text-xs font-bold uppercase hover:bg-blue-700"
                                            >
                                                <PlayCircle className="w-3.5 h-3.5" />
                                                <span>Start</span>
                                            </button>
                                        )}
                                        <button
                                            onClick={async () => {
                                                await handleUpdateTask(selectedTask._id, { status: 'Skipped' });
                                                setIsModalOpen(false);
                                                fetchTasks();
                                            }}
                                            className="flex items-center space-x-1 px-3 py-2 text-slate-500 hover:bg-slate-100 text-xs font-bold uppercase"
                                        >
                                            <SkipForward className="w-3.5 h-3.5" />
                                            <span>Skip</span>
                                        </button>
                                    </>
                                )}
                            </div>
                            <div className="flex items-center space-x-2">
                                <button
                                    onClick={() => setIsModalOpen(false)}
                                    className="px-4 py-2 text-xs font-bold uppercase text-slate-500 hover:text-black"
                                >
                                    Close
                                </button>
                                {selectedTask.status !== 'Completed' && (
                                    <button
                                        onClick={handleCompleteTask}
                                        disabled={isSubmitting}
                                        className="px-6 py-2 bg-emerald-600 text-white text-xs font-bold uppercase hover:bg-emerald-700 disabled:opacity-50 flex items-center space-x-2"
                                    >
                                        {isSubmitting && <Loader2 className="w-3 h-3 animate-spin" />}
                                        <CheckCircle2 className="w-4 h-4" />
                                        <span>Complete</span>
                                    </button>
                                )}
                            </div>
                        </div>
                    </div>
                </div>
            )}

            {/* New Task Modal */}
            {isNewTaskModalOpen && (
                <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/50 backdrop-blur-sm p-4">
                    <div className="bg-white w-full max-w-md shadow-2xl animate-in fade-in zoom-in duration-200">
                        <div className="flex items-center justify-between px-6 py-4 border-b border-slate-100">
                            <h2 className="text-sm font-black uppercase tracking-widest text-slate-900">New Retention Task</h2>
                            <button onClick={() => setIsNewTaskModalOpen(false)} className="text-slate-400 hover:text-black">
                                <X className="w-5 h-5" />
                            </button>
                        </div>

                        <form onSubmit={handleCreateTask} className="p-6 space-y-4">
                            <div>
                                <label className="text-[10px] font-bold text-slate-500 uppercase block mb-1">Client *</label>
                                <select
                                    required
                                    value={newTask.client}
                                    onChange={(e) => setNewTask({ ...newTask, client: e.target.value })}
                                    className="w-full px-3 py-2 border border-slate-200 text-sm focus:outline-none focus:border-black"
                                >
                                    <option value="">Select Client</option>
                                    {clients.map(c => (
                                        <option key={c._id} value={c._id}>{c.name}</option>
                                    ))}
                                </select>
                            </div>

                            <div className="grid grid-cols-2 gap-4">
                                <div>
                                    <label className="text-[10px] font-bold text-slate-500 uppercase block mb-1">Type</label>
                                    <select
                                        value={newTask.type}
                                        onChange={(e) => setNewTask({ ...newTask, type: e.target.value })}
                                        className="w-full px-3 py-2 border border-slate-200 text-sm focus:outline-none focus:border-black"
                                    >
                                        {['Followup Call', 'Followup Email', 'Check-in', 'Re-engagement', 'Win-back', 'Feedback Request', 'Upsell Opportunity'].map(t => (
                                            <option key={t} value={t}>{t}</option>
                                        ))}
                                    </select>
                                </div>
                                <div>
                                    <label className="text-[10px] font-bold text-slate-500 uppercase block mb-1">Priority</label>
                                    <select
                                        value={newTask.priority}
                                        onChange={(e) => setNewTask({ ...newTask, priority: e.target.value })}
                                        className="w-full px-3 py-2 border border-slate-200 text-sm focus:outline-none focus:border-black"
                                    >
                                        {['Low', 'Medium', 'High', 'Critical'].map(p => (
                                            <option key={p} value={p}>{p}</option>
                                        ))}
                                    </select>
                                </div>
                            </div>

                            <div className="grid grid-cols-2 gap-4">
                                <div>
                                    <label className="text-[10px] font-bold text-slate-500 uppercase block mb-1">Due Date</label>
                                    <input
                                        type="date"
                                        value={newTask.dueDate}
                                        onChange={(e) => setNewTask({ ...newTask, dueDate: e.target.value })}
                                        className="w-full px-3 py-2 border border-slate-200 text-sm focus:outline-none focus:border-black"
                                    />
                                </div>
                                <div>
                                    <label className="text-[10px] font-bold text-slate-500 uppercase block mb-1">Assign To</label>
                                    <select
                                        value={newTask.assignedTo}
                                        onChange={(e) => setNewTask({ ...newTask, assignedTo: e.target.value })}
                                        className="w-full px-3 py-2 border border-slate-200 text-sm focus:outline-none focus:border-black"
                                    >
                                        <option value="">Unassigned</option>
                                        {users.map(u => (
                                            <option key={u._id} value={u._id}>{u.firstName} {u.lastName}</option>
                                        ))}
                                    </select>
                                </div>
                            </div>

                            <div>
                                <label className="text-[10px] font-bold text-slate-500 uppercase block mb-1">Notes</label>
                                <textarea
                                    value={newTask.notes}
                                    onChange={(e) => setNewTask({ ...newTask, notes: e.target.value })}
                                    placeholder="Add any notes or context..."
                                    className="w-full px-3 py-2 border border-slate-200 text-sm focus:outline-none focus:border-black h-20 resize-none"
                                />
                            </div>

                            <div className="flex justify-end space-x-2 pt-4">
                                <button
                                    type="button"
                                    onClick={() => setIsNewTaskModalOpen(false)}
                                    className="px-4 py-2 text-xs font-bold uppercase text-slate-500 hover:text-black"
                                >
                                    Cancel
                                </button>
                                <button
                                    type="submit"
                                    disabled={isSubmitting}
                                    className="px-6 py-2 bg-black text-white text-xs font-bold uppercase hover:bg-slate-800 disabled:opacity-50 flex items-center space-x-2"
                                >
                                    {isSubmitting && <Loader2 className="w-3 h-3 animate-spin" />}
                                    <span>Create Task</span>
                                </button>
                            </div>
                        </form>
                    </div>
                </div>
            )}
        </div>
    );
}

// Reusable Pipeline Grid View
function PipelineGridView({ 
    clients, 
    onClientClick, 
    onClientDrop,
    draggedClient,
    setDraggedClient,
    dragOverStage,
    setDragOverStage
}: { 
    clients: Client[], 
    onClientClick: (client: Client) => void,
    onClientDrop: (e: React.DragEvent, status: string) => void,
    draggedClient: Client | null,
    setDraggedClient: (client: Client | null) => void,
    dragOverStage: string | null,
    setDragOverStage: (stage: string | null) => void
}) {
    return (
        <div className="flex-1 overflow-x-auto p-6">
            <div className="flex space-x-4 h-full min-w-max">
                {PIPELINE_STAGES.map((stage) => (
                    <div
                        key={stage.id}
                        className={cn(
                            "flex flex-col w-[360px] bg-white border shadow-sm h-full transition-all",
                            dragOverStage === stage.id && "ring-2 ring-blue-400 ring-offset-2"
                        )}
                        onDragOver={(e) => {
                            e.preventDefault();
                            setDragOverStage(stage.id);
                        }}
                        onDragLeave={() => setDragOverStage(null)}
                        onDrop={(e) => onClientDrop(e, stage.id)}
                    >
                        {/* Stage Header */}
                        <div className={cn("px-4 py-3 border-b flex items-center justify-between shrink-0", stage.bgColor)}>
                            <div className="flex items-center space-x-2">
                                <span className={stage.color}>{stage.icon}</span>
                                <span className={cn("text-xs font-black uppercase tracking-wider", stage.color)}>{stage.label}</span>
                            </div>
                            <span className={cn("text-sm font-black", stage.color)}>
                                {clients.filter(c => (c.contactStatus || 'Uncategorized') === stage.id).length}
                            </span>
                        </div>

                        {/* Stage Content */}
                        <div className="flex-1 overflow-y-auto p-3 space-y-2 scrollbar-custom">
                            {clients.filter(c => (c.contactStatus || 'Uncategorized') === stage.id).length === 0 ? (
                                <div className="flex flex-col items-center justify-center py-8 text-slate-400 opacity-50">
                                    <p className="text-[10px] font-bold uppercase italic">Stage Empty</p>
                                </div>
                            ) : (
                                clients.filter(c => (c.contactStatus || 'Uncategorized') === stage.id).map((client) => (
                                    <div
                                        key={client._id}
                                        draggable
                                        onDragStart={(e) => {
                                            setDraggedClient(client);
                                            e.dataTransfer.effectAllowed = 'move';
                                        }}
                                        onClick={() => onClientClick(client)}
                                        className={cn(
                                            "bg-white border p-3 cursor-grab animate-in fade-in slide-in-from-bottom-2 duration-300 active:cursor-grabbing hover:shadow-md transition-all group",
                                            draggedClient?._id === client._id && "opacity-50 scale-95"
                                        )}
                                    >
                                        <div className="flex items-start justify-between mb-2">
                                            <div className="flex items-center space-x-2">
                                                <div className="w-6 h-6 bg-slate-100 flex items-center justify-center text-[10px] font-black text-slate-600 uppercase border border-slate-200">
                                                    {client.name?.charAt(0)}
                                                </div>
                                                <span className="text-[10px] font-bold text-slate-400 uppercase tracking-tighter">Client Profile</span>
                                            </div>
                                            <GripVertical className="w-4 h-4 text-slate-300 opacity-0 group-hover:opacity-100 transition-opacity" />
                                        </div>

                                        <div className="text-sm font-black text-slate-900 mb-3 truncate group-hover:text-blue-600 transition-colors">
                                            {client.name}
                                        </div>

                                        <div className="grid grid-cols-2 gap-4 mb-3">
                                            <div>
                                                <div className="text-[9px] font-bold text-slate-400 uppercase mb-1">Total Revenue</div>
                                                <div className="flex items-center space-x-1">
                                                    <DollarSign className="w-3 h-3 text-emerald-500" />
                                                    <span className="text-xs font-black text-slate-700">
                                                        {client.totalRevenue?.toLocaleString() || '0'}
                                                    </span>
                                                </div>
                                            </div>
                                            <div>
                                                <div className="text-[9px] font-bold text-slate-400 uppercase mb-1">Activities</div>
                                                <div className="flex items-center space-x-1">
                                                    <Activity className="w-3 h-3 text-purple-500" />
                                                    <span className="text-xs font-black text-slate-700">
                                                        {client.activityCount || 0}
                                                    </span>
                                                </div>
                                            </div>
                                        </div>

                                        <div className="flex items-center justify-between pt-2 border-t border-slate-50">
                                            <div className="flex items-center space-x-2">
                                                {client.phones?.[0] && (
                                                    <div className="w-5 h-5 bg-slate-50 flex items-center justify-center rounded-full">
                                                        <Phone className="w-2.5 h-2.5 text-slate-400" />
                                                    </div>
                                                )}
                                                {client.emails?.[0] && (
                                                    <div className="w-5 h-5 bg-slate-50 flex items-center justify-center rounded-full">
                                                        <Mail className="w-2.5 h-2.5 text-slate-400" />
                                                    </div>
                                                )}
                                            </div>
                                            {client.lastActivity && (
                                                <div className="text-[9px] font-bold text-slate-400 uppercase">
                                                    {new Date(client.lastActivity).toLocaleDateString('en-US', { month: 'short', day: 'numeric' })}
                                                </div>
                                            )}
                                        </div>
                                    </div>
                                ))
                            )}
                        </div>
                    </div>
                ))}
            </div>
        </div>
    );
}
